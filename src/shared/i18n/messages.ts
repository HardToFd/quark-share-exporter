export function translateExternalMessage(locale: Locale, message: string): string {
  if (locale !== 'en' || !message) return message
  const exact = externalEnglish.get(message)
  if (exact) return exact
  for (const [pattern, replacement] of externalEnglishPatterns) {
    const match = message.match(pattern)
    if (match) return replacement(...match.slice(1))
  }
  return message
}
